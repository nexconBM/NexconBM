/* Nexcon site language switcher: English | Simplified Chinese | Traditional Chinese.
   Relies on translations.js being loaded first (and, on Simplified pages, translations-hans.js,
   which replaces translations.zh with its Simplified copy).
   Each language has its own URLs: English at /page/, Simplified at /zh-hans/page/, Traditional at
   /zh/page/ (the Chinese ones generated by build.py, which also bakes the Chinese text into those
   pages so search engines can index it). The page's language is its <html lang>, and the switcher
   (#langSwitch, "Eng | 繁 | 简") is three plain links to the other versions, each with data-lang.
   Elements opt in with data-i18n="key" (sets textContent) or data-i18n data-i18n-html="key" (sets
   innerHTML, for text containing tags); applying the dictionary here still matters for text that
   scripts add to the page after it loads. */
(function () {
  // Only written when the visitor clicks the switcher. (The old "nexcon-lang" key was saved on
  // every page view, so it can't tell a real choice from a default "en" -- don't reuse it.)
  var STORAGE_KEY = "nexcon-lang-choice";
  var htmlLang = document.documentElement.lang;
  var pageLang = htmlLang === "zh-Hans" ? "zh-hans" : /^zh/i.test(htmlLang) ? "zh-hant" : "en";

  function storedLang() {
    try {
      var lang = localStorage.getItem(STORAGE_KEY); // null if never set
      // Before the 简/繁 split, "zh" meant the only Chinese version there was: Traditional.
      return lang === "zh" ? "zh-hant" : lang;
    } catch (e) {
      return null; // storage unavailable (some file:// or private-browsing contexts)
    }
  }

  function storeLang(lang) {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {
      /* storage unavailable: the visitor just won't be sent to their last-used language */
    }
  }

  var switcher = document.getElementById("langSwitch");

  function hrefFor(lang) {
    var link = switcher && switcher.querySelector('a[data-lang="' + lang + '"]');
    return link && link.getAttribute("href");
  }

  // Remember the language the visitor picked with the switcher: someone who chose 简 and later
  // opens an English URL is sent to its Simplified copy. Visitors who never clicked it (and
  // search crawlers, which keep no localStorage) always see the page they asked for.
  var remembered = storedLang();
  if (remembered && remembered !== pageLang && hrefFor(remembered)) {
    location.replace(hrefFor(remembered) + location.hash);
    return;
  }

  // The Noto Sans fonts are large (each stylesheet alone is ~170 KB). Chinese pages already link
  // theirs in the <head>; this is only a fallback for any page that doesn't.
  function loadCjkFont(family) {
    if (document.querySelector('link[href*="' + family + '"]')) return;
    var link = document.createElement("link");
    link.rel = "stylesheet";
    link.href = "https://fonts.googleapis.com/css2?family=" + family + ":wght@400;500;600;700;800&display=swap";
    document.head.appendChild(link);
  }

  function applyLang(lang) {
    if (lang === "zh-hans") loadCjkFont("Noto+Sans+SC");
    if (lang === "zh-hant") loadCjkFont("Noto+Sans+TC");
    var dict = (lang === "en" ? translations.en : translations.zh) || translations.en;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (dict[key] === undefined) return;
      if (el.hasAttribute("data-i18n-html")) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    });
  }

  document.addEventListener("DOMContentLoaded", function () {
    applyLang(pageLang);

    if (switcher) {
      switcher.addEventListener("click", function (event) {
        var link = event.target.closest("a[data-lang]");
        if (!link) return;
        storeLang(link.getAttribute("data-lang"));
        if (location.hash) {
          // Keep the visitor on the same section of the other version.
          event.preventDefault();
          location.href = link.getAttribute("href") + location.hash;
        }
      });
    }
  });
})();
