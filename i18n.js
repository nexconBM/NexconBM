/* Nexcon site language toggle: English <-> Traditional Chinese.
   Relies on translations.js being loaded first.
   Each language has its own URLs: English at /page/, Chinese at /zh/page/ (generated by
   build.py, which also bakes the Chinese text into those pages so search engines can index it).
   The page's language is its <html lang>, and the toggle (#langToggle) navigates to the other
   version via its data-alt-href. Elements opt in with data-i18n="key" (sets textContent)
   or data-i18n data-i18n-html="key" (sets innerHTML, for text containing tags); applying the
   dictionary here still matters for text that scripts add to the page after it loads. */
(function () {
  // Only written when the visitor clicks the toggle. (The old "nexcon-lang" key was saved on
  // every page view, so it can't tell a real choice from a default "en" -- don't reuse it.)
  var STORAGE_KEY = "nexcon-lang-choice";
  var pageLang = /^zh/i.test(document.documentElement.lang) ? "zh" : "en";

  function storedLang() {
    try {
      return localStorage.getItem(STORAGE_KEY); // null if never set
    } catch (e) {
      return null; // storage unavailable (some file:// or private-browsing contexts)
    }
  }

  function storeLang(lang) {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {
      /* storage unavailable: the visitor just won't be sent to their last-used language */
    }
  }

  var toggle = document.getElementById("langToggle");
  var altHref = toggle && toggle.getAttribute("data-alt-href");

  // Remember the language the visitor picked with the toggle: someone who switched to Chinese
  // and later opens an English URL is sent to its Chinese copy. Visitors who never clicked it
  // (and search crawlers, which keep no localStorage) always see the page they asked for.
  var remembered = storedLang();
  if (altHref && remembered && remembered !== pageLang) {
    location.replace(altHref + location.hash);
    return;
  }

  // Noto Sans TC is large (its stylesheet alone is ~170 KB). Chinese pages already link it in
  // their <head>; this is only a fallback for any page that doesn't.
  function loadCjkFont() {
    if (document.querySelector('link[href*="Noto+Sans+TC"]')) return;
    var link = document.createElement("link");
    link.rel = "stylesheet";
    link.href = "https://fonts.googleapis.com/css2?family=Noto+Sans+TC:wght@400;500;600;700;800&display=swap";
    document.head.appendChild(link);
  }

  function applyLang(lang) {
    if (lang === "zh") loadCjkFont();
    var dict = translations[lang] || translations.en;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (dict[key] === undefined) return;
      if (el.hasAttribute("data-i18n-html")) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    });
  }

  document.addEventListener("DOMContentLoaded", function () {
    applyLang(pageLang);

    if (toggle && altHref) {
      toggle.addEventListener("click", function () {
        storeLang(pageLang === "en" ? "zh" : "en");
        location.href = altHref + location.hash;
      });
    }
  });
})();
